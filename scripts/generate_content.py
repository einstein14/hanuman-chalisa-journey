def audio_path(vtype: str, num_in_type: int) -> str | None:
    if vtype == "introductory_doha":
        return f"/audio/intro-doha-{num_in_type:02d}.m4a"
    if vtype == "concluding_doha":
        return "/audio/concluding-doha.m4a"
    return f"/audio/verse-{num_in_type:02d}.m4a"


def build_verse(vid: int, vtype: str, num: int, hindi: str) -> dict:
    idx = vid - 1
    words = [w for w in re.split(r"\s+", hindi.replace("।", " ").replace("॥", "")) if w]
    blank, opts = GAME_BLANKS[idx]
    lines = [ln.strip() for ln in hindi.replace("॥", "|").split("|") if ln.strip()]
    if len(lines) < 2:
        parts = hindi.split("।")
        lines = [p.strip() + "।" for p in parts if p.strip()][:2]
    wrong = []
    for j in [1, 2, 3]:
        if idx + j < len(ME_EN):
            wrong.append(ME_EN[(idx + j) % len(ME_EN)])
    return {
        "id": vid,
        "type": vtype,
        "number_in_type": num,
        "hindi": hindi,
        "telugu": TE_TRANS[idx],
        "english_transliteration": EN_TRANS[idx],
        "meaning_english": ME_EN[idx],
        "meaning_telugu": ME_TE[idx],
        "why_special_english": WHY_EN[idx],
        "why_special_telugu": WHY_TE[idx],
        "audio": audio_path(vtype, num),
        "timings": None,
        "game": {
            "blank_word": blank,
            "blank_options": opts,
            "arrange_lines": lines[:2] if len(lines) >= 2 else lines,
            "wrong_meanings_en": wrong[:2],
        },
    }


